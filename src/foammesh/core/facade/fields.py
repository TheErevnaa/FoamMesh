"""AF2 field descriptor registry generated from ``configurations_schema``.

The registry gives every editable engineering value a stable semantic field ID
(Â§6.2) plus type, unit, constraints, default, applicability, invalidation, and
UI-location metadata. Base descriptors are generated by walking the SimpleDB
schema; hand-authored metadata (units/docs/dependencies/applicability/impact/
UI) is layered on from :mod:`foammesh.core.facade.field_metadata`, because that
information cannot be inferred from the legacy type system.

The generated semantic IDs are a frozen part of the AF1V contract for the ten
AF1V fields; AF2 adds the rest against the same dotted ``area.group.field``
shape.
"""
